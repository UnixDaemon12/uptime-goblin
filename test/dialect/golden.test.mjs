// Golden DDL (roadmap §10.5, a 1.5 gate): the DDL every engine gets for the table registry and
// for the reference tables is pinned in test/dialect/golden/<set>-<dialect>.sql. A change to a
// table or to a dialect's DDL rules shows up as a diff here. (The name uses "-", not ".": the
// release packager refuses any file named like a database, such as *.sqlite.*.) After reviewing
// the change, regenerate with:
//   UPDATE_GOLDEN=1 node --test --import ./test/setup.mjs test/dialect/golden.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { renderSchema, renderTable, requiredDialects } from '../../lib/db/dialect/schema.mjs';
import { loadDialect, DIALECTS } from '../../lib/db/dialect/index.mjs';
import { referenceTables } from './fixtures/reference-schema.mjs';

const directory = fileURLToPath(new URL('./golden/', import.meta.url));
const update = process.env.UPDATE_GOLDEN === '1';
const dialects = Object.fromEntries(
  await Promise.all(DIALECTS.map(async name => [name, await loadDialect(name)]))
);

// The registry is lane P's (lib/db/registry.mjs); its DSL tables are pinned when it exists.
let registry = null;
try {
  ({ registry } = await import('../../lib/db/registry.mjs'));
} catch (error) {
  if (error.code !== 'ERR_MODULE_NOT_FOUND') throw error;
}

const sets = { reference: referenceTables };
if (registry) sets.registry = registry.dslTables;

const goldenName = (set, dialect) => `${set}-${dialect}.sql`;

const header = (set, dialect) =>
  `-- Golden DDL: ${set} tables, ${dialect}. Generated by test/dialect/golden.test.mjs; do not edit.\n` +
  `-- Regenerate after review: UPDATE_GOLDEN=1 node --test --import ./test/setup.mjs test/dialect/golden.test.mjs\n\n`;

for (const [set, tables] of Object.entries(sets))
  for (const name of DIALECTS)
    test(`golden DDL: ${set} tables on ${name}`, () => {
      const file = path.join(directory, goldenName(set, name));
      const rendered = header(set, name) + renderSchema(dialects[name], tables);
      if (update) {
        fs.mkdirSync(directory, { recursive: true });
        fs.writeFileSync(file, rendered);
      }
      assert.ok(
        fs.existsSync(file),
        `${path.relative(process.cwd(), file)} is missing: run with UPDATE_GOLDEN=1`
      );
      assert.equal(
        rendered,
        fs.readFileSync(file, 'utf8'),
        `${goldenName(set, name)} changed: review, then UPDATE_GOLDEN=1`
      );
    });

test('no golden file is left over from a removed set or dialect', () => {
  const expected = new Set(
    Object.keys(sets).flatMap(set => DIALECTS.map(name => goldenName(set, name)))
  );
  const present = fs.existsSync(directory)
    ? fs.readdirSync(directory).filter(file => file.endsWith('.sql'))
    : [];
  if (!registry) for (const name of DIALECTS) expected.add(goldenName('registry', name)); // kept until the registry returns
  assert.deepEqual(
    present.filter(file => !expected.has(file)),
    []
  );
});

// scripts/package-release.mjs refuses release inputs named like data or key files; test/ ships in
// the source release, so a golden file named reference.sqlite.sql would block packaging.
test('golden files are named so the release packager accepts them', () => {
  const privateName = /\.(?:sqlite|db|pem|key|p12|pfx|log)(?:$|\.)/i;
  const files = fs.readdirSync(directory);
  assert.ok(files.length >= DIALECTS.length);
  assert.deepEqual(
    files.filter(file => privateName.test(file)),
    []
  );
});

test('the golden SQLite DDL of every set runs on a fresh database', () => {
  for (const tables of Object.values(sets)) {
    const db = new DatabaseSync(':memory:');
    try {
      for (const spec of tables.filter(t => t.modes.includes('single')))
        for (const statement of renderTable(dialects.sqlite, spec)) db.exec(statement);
    } finally {
      db.close();
    }
  }
});

test('every DSL table renders on every engine its modes need', () => {
  for (const tables of Object.values(sets))
    for (const spec of tables)
      for (const name of requiredDialects(spec.modes))
        assert.ok(renderTable(dialects[name], spec).length >= 1, `${spec.name} on ${name}`);
});

test('the server DDL follows the §10.4 type contract', () => {
  const pg = renderSchema(dialects.postgres, referenceTables);
  const ms = renderSchema(dialects.mssql, referenceTables);
  const lite = renderSchema(dialects.sqlite, referenceTables);
  assert.match(
    lite,
    /"dedupe_key" TEXT COLLATE BINARY NOT NULL CHECK \(length\("dedupe_key"\) <= 128\)/
  );
  assert.match(
    pg,
    /"dedupe_key" text COLLATE "C" NOT NULL CHECK \(char_length\("dedupe_key"\) <= 128\)/
  );
  // text(n) is n characters everywhere; SQL Server's LEN() would not count trailing spaces.
  assert.match(
    ms,
    /\[dedupe_key\] varchar\(512\) COLLATE Latin1_General_100_BIN2_UTF8 NOT NULL CHECK \(LEN\(REPLACE\(\[dedupe_key\], ' ', '\.'\)\) <= 128\)/
  );
  assert.doesNotMatch(ms, /CHECK \(LEN\(\[/);
  assert.match(pg, /"payload" jsonb NOT NULL/);
  assert.match(ms, /\[payload\] varchar\(max\) NOT NULL CHECK \(ISJSON\(\[payload\]\) = 1\)/);
  assert.match(pg, /"weight" double precision/);
  assert.match(ms, /\[weight\] float/);
  assert.doesNotMatch(ms, /\breal\b|nvarchar|datetime/i);
  assert.match(
    ms,
    /CREATE UNIQUE NONCLUSTERED INDEX \[ref_outbox_dedupe_key_key\] ON \[orbit\].\[ref_outbox\] \(\[dedupe_key\]\) WITH \(IGNORE_DUP_KEY = ON\)/
  );
  assert.match(ms, /PRIMARY KEY CLUSTERED \(\[key\]\) WITH \(IGNORE_DUP_KEY = ON\)/);
  assert.match(pg, /"id" bigint GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(ms, /\[id\] bigint IDENTITY\(1,1\) NOT NULL/);
  assert.match(pg, /PARTITION BY RANGE \("slot"\)/);
  assert.match(ms, /ON \[ref_head_ps\] \(\[slot\]\)/);
  assert.match(ms, /WHERE \[weight\] IS NOT NULL AND \[enabled\] = 1/);
  assert.match(pg, /WHERE "weight" IS NOT NULL AND "enabled" = TRUE/);
});
