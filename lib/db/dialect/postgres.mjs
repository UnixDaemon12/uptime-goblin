// The PostgreSQL dialect: a render-only skeleton in 1.5. It renders statements, DDL and error
// classes so the contract and golden DDL are tested from 1.5, but nothing executes it until the
// 1.7 preview (lib/db/postgres.mjs, which alone may import the `postgres` driver). Reach it only
// through `loadDialect('postgres')` (a dynamic import): SQLite mode must never resolve it.
//
// Contract (roadmap §10.4): `$n` placeholders; ON CONFLICT upserts with the batch de-duplicated
// and keys sorted; RETURNING; claims with FOR UPDATE SKIP LOCKED and fences with FOR SHARE; the
// clock is clock_timestamp() (never now(), which is the transaction's start); BIGINT
// milliseconds, jsonb, double precision and bytea; key text in COLLATE "C"; schema `orbit`.
import { fragment } from '../sql.mjs';
import { createDialect, classifier } from './base.mjs';

const quote = name => `"${name.replaceAll('"', '""')}"`;
const tagged = (strings, values = []) => fragment(strings, values, 'postgres');

/**
 * SQLSTATE → error class (https://www.postgresql.org/docs/current/errcodes-appendix.html).
 * Exact codes win over their two-character class.
 */
export const POSTGRES_CODES = Object.freeze({
  exact: Object.freeze({
    40001: 'retry', // serialization_failure
    '40P01': 'retry', // deadlock_detected
    40003: 'unavailable', // statement_completion_unknown
    23505: 'unique', // unique_violation
    '23P01': 'unique', // exclusion_violation
    23502: 'poison', // not_null_violation
    23503: 'poison', // foreign_key_violation
    23514: 'poison', // check_violation (a missing partition is `full`, see below)
    53100: 'full', // disk_full
    53200: 'unavailable', // out_of_memory
    53300: 'unavailable', // too_many_connections
    '55P03': 'timeout', // lock_not_available (lock_timeout)
    57014: 'timeout', // query_canceled (statement_timeout)
    '57P01': 'unavailable', // admin_shutdown
    '57P02': 'unavailable', // crash_shutdown
    '57P03': 'unavailable', // cannot_connect_now
    '57P04': 'fatal', // database_dropped
    25006: 'unavailable', // read_only_sql_transaction (connected to a standby after failover)
    58030: 'unavailable', // io_error
    XX001: 'fatal', // data_corrupted
    XX002: 'fatal', // index_corrupted
  }),
  byClass: Object.freeze({
    '08': 'unavailable', // connection exception
    22: 'poison', // data exception (overflow, bad text, invalid JSON)
    23: 'poison', // other integrity constraint violations
    28: 'fatal', // invalid authorization
    '3D': 'fatal', // invalid catalog name
    42: 'fatal', // syntax error or access rule violation
    53: 'unavailable', // insufficient resources
    54: 'fatal', // program limit exceeded
    '0A': 'fatal', // feature not supported
    XX: 'fatal', // internal error
  }),
  // Errors raised by the client before or instead of a server reply.
  client: Object.freeze({
    ECONNREFUSED: 'unavailable',
    ECONNRESET: 'unavailable',
    EPIPE: 'unavailable',
    ENOTFOUND: 'unavailable',
    EHOSTUNREACH: 'unavailable',
    ENETUNREACH: 'unavailable',
    ETIMEDOUT: 'timeout',
    CONNECTION_CLOSED: 'unavailable',
    CONNECTION_ENDED: 'unavailable',
    CONNECTION_DESTROYED: 'unavailable',
    CONNECT_TIMEOUT: 'timeout',
  }),
});

const sqlState = /^[0-9A-Z]{5}$/;
const classify = classifier([
  // Client codes first: some (EPIPE) look like a SQLSTATE.
  error => POSTGRES_CODES.client[error?.code] ?? null,
  error => {
    const code = typeof error?.code === 'string' && sqlState.test(error.code) ? error.code : null;
    if (!code) return null;
    // PostgreSQL reports a row with no partition to hold it as a check violation (23514).
    if (code === '23514' && /no partition of relation/i.test(error.message || '')) return 'full';
    return POSTGRES_CODES.exact[code] ?? POSTGRES_CODES.byClass[code.slice(0, 2)] ?? 'fatal';
  },
]);

const intervals = { hour: 'hour', day: 'day', month: 'month' };

function ddl(schema) {
  const tableName = name => `${quote(schema)}.${quote(name)}`;
  return Object.freeze({
    singleOnly: false,
    quote,
    tableName,
    idColumn: 'bigint GENERATED BY DEFAULT AS IDENTITY',
    idIsKey: false,
    keyCollation: 'COLLATE "C"',
    boolean: value => (value ? 'TRUE' : 'FALSE'),
    type: column =>
      ({
        text: 'text',
        bigint: 'bigint',
        double: 'double precision',
        bool: 'boolean',
        bytes: 'bytea',
        json: 'jsonb',
      })[column.type],
    checks: (name, column) =>
      column.type === 'text' && column.max ? [`char_length(${name}) <= ${column.max}`] : [],
    primaryKey: (name, columns) => `CONSTRAINT ${quote(name)} PRIMARY KEY (${columns.join(', ')})`,
    createTable: (name, lines, spec) =>
      `CREATE TABLE ${name} (\n  ${lines.join(',\n  ')}\n)${
        spec.partition
          ? ` PARTITION BY RANGE (${quote(spec.partition.column)}) /* ${intervals[spec.partition.interval]} partitions: the partition manager */`
          : ''
      }`,
    createIndex: ({ name, unique, table, keys, where }) =>
      `CREATE ${unique ? 'UNIQUE ' : ''}INDEX ${quote(name)} ON ${table} (${keys})${where ? ` WHERE ${where}` : ''}`,
  });
}

// Catalog queries (base.mjs) over pg_catalog, for the dialect's schema (bound as a value).
// Partitioned tables are listed once: their partitions belong to the partition manager.
const relations =
  'FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = ';
const ownTables = " AND c.relkind IN ('r', 'p') AND NOT c.relispartition";
function catalog(schema) {
  return Object.freeze({
    tables: () =>
      tagged(
        [`SELECT c.relname AS name ${relations}`, `${ownTables} ORDER BY c.relname`],
        [schema]
      ),
    tableExists: name =>
      tagged(
        [`SELECT 1 AS present ${relations}`, `${ownTables} AND c.relname = `, ''],
        [schema, name]
      ),
    columns: name =>
      tagged(
        [
          `SELECT a.attname AS name FROM pg_catalog.pg_attribute a JOIN pg_catalog.pg_class c ON c.oid = a.attrelid JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = `,
          `${ownTables} AND c.relname = `,
          ' AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum',
        ],
        [schema, name]
      ),
    indexes: () =>
      tagged(
        [
          `SELECT i.relname AS name, c.relname AS "table" FROM pg_catalog.pg_index x JOIN pg_catalog.pg_class i ON i.oid = x.indexrelid JOIN pg_catalog.pg_class c ON c.oid = x.indrelid JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = `,
          `${ownTables} ORDER BY i.relname`,
        ],
        [schema]
      ),
  });
}

/**
 * A PostgreSQL dialect (render only in 1.5). Options: `identifiers` (the registry's names) and
 * `schema` (default `orbit`; DDL is schema-qualified, statements rely on search_path = orbit).
 */
export function createPostgresDialect({ identifiers, schema = 'orbit' } = {}) {
  return createDialect({
    name: 'postgres',
    executable: false,
    identifiers,
    caps: {
      cluster: true,
      partitions: true,
      skipLocked: true,
      onlineIndex: true,
      txDdl: true,
      bulkLoad: true,
      dbClock: true,
    },
    quote,
    placeholder: n => `$${n}`,
    bind: value => ({ value }),
    json: placeholder => `CAST(${placeholder} AS jsonb)`,
    returning: 'suffix',
    sortKeys: true,
    clock: () => tagged(['CAST(floor(extract(epoch FROM clock_timestamp()) * 1000) AS bigint)']),
    limit: (state, n, offset) =>
      offset ? `LIMIT ${state.bind(n)} OFFSET ${state.bind(offset)}` : `LIMIT ${state.bind(n)}`,
    orderTerm: (expression, desc, nulls) =>
      tagged(
        [
          '',
          ` ${desc ? 'DESC' : 'ASC'}${nulls === 'not null' ? '' : ` NULLS ${nulls.toUpperCase()}`}`,
        ],
        [expression]
      ),
    locks: {
      share: { hint: '', tail: 'FOR SHARE' },
      claim: { hint: '', tail: 'FOR UPDATE SKIP LOCKED' },
    },
    classify,
    catalog: catalog(schema),
    ddl: ddl(schema),
  });
}

export const postgres = createPostgresDialect();
